export function sum(num1: number, num2: number): number {
  return num1 + num2;
}

export function rest(num1: number, num2: number): number {
  return num1 - num2;
}

export function multiple(num1: number, num2: number): number {
  return num1 * num2;
}

export function div(num1: number, num2: number): number {
  return num1 / num2;
}

export const PI: number = 3.1416;
